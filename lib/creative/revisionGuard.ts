// ============================================================
// Revision Guard（修改守门）—— 纯函数，零 LLM
//
// 存在意义：Work Agent 不是"照做按钮"。
//   用户能描述的是"哪里不舒服"，不一定知道"什么改法会把它改坏"。
//   最典型的一句：「把所有专业词换成高级词」——照做的结果是
//   读者读不懂、作者不像自己，而用户此刻并不知道这一点。
//
// 守门的边界（改动前必读）：
//   1. **只提示，不阻拦。** 结论交给用户，AI 无权替他放弃一个改法
//   2. **只拦有确定危害的类别。** 列举式规则，宁可少报不可误报——
//      动不动弹窗的守门等于没有守门，用户会学会无视它
//   3. **每条必须给出替代方案。** 只说"这样不好"是把问题丢回给用户
//
// 为什么不用 LLM 判断：
//   LLM 会把"加金句""写得高级点"判成合理优化（它本来就擅长这个），
//   而"这符不符合这位创作者"恰恰是可枚举的规则问题。
// ============================================================

import type { AgentAdvisory } from './workAgent'

interface GuardRule {
  id: string
  patterns: RegExp[]
  /** 这条改法的具体危害（一句话，直接展示） */
  concern: string
  /** 为什么有害（讲清机制，让用户能自己判断要不要坚持） */
  why: string
  /** 替代改法（可执行，不是空话） */
  better: string
}

/**
 * 风险规则表。顺序即优先级，命中第一条即返回。
 *
 * 收录标准：该改法在这条产品线上**确定**会伤害作品，且与产品定位冲突。
 * 没有把握的（风格偏好、篇幅取舍）一律不收——那属于用户自己的选择。
 */
const GUARD_RULES: GuardRule[] = [
  {
    id: 'terminology_swap',
    patterns: [
      /(换(成|为)|改用|加(点|些)?)(更)?(高级|高深|专业|华丽|高大上|学术)(的)?(词|词汇|术语|表达|说法)/,
      /(堆砌|堆)(术语|名词|概念|高级词)/,
      /(term|vocab)/i,
    ],
    concern: '把词换"高级"会让普通读者读不懂，也会盖掉你原本的说话方式',
    why: '术语增加的是信息门槛，不是说服力。读者卡在不认识的词上时，后面的论证一个字也进不去',
    better: '保留核心概念的原词，用一句具体案例或类比把它讲明白——专业感来自解释得透，不来自词生僻',
  },
  {
    id: 'hollow_punchline',
    patterns: [
      /(每(句|段|个)|处处|到处)都?(要|加)(金句|金句感|爆点|亮点)/,
      /(再|更)(煽情|煽一点|燃|炸裂|炸一点)/,
      /(标题党|博眼球|吸引眼球)(一点|些)?/,
      /(加(点|些)?)(网络热词|流行语)/,
    ],
    concern: '通篇堆"金句/爆点"会让文章变成没有信息的情绪碎片',
    why: '金句的力量来自前后文的铺垫。每段都是高潮，读者反而记不住任何一句',
    better: '挑 1-2 个真正有观点的位置做重点强化，其余段落保持平实叙述，把起伏留给最重要的那句',
  },
  {
    id: 'length_padding',
    patterns: [
      /(拉长|写长|加长|扩写|再长)(一点|一些|些)?/,
      /(到|够|满)\s*\d{3,}\s*字/,
      /(再)?(多写|加点字|凑字数)/,
    ],
    concern: '为凑长度扩写会稀释信息密度，读者会感到"说了半天没东西"',
    why: '文章变长但每段的单位信息量下降，完读率通常先掉，而不是先涨',
    better: '先告诉我要补的是哪一类内容（案例 / 论证 / 背景），补实一点的内容比单纯拉长更有效',
  },
  {
    id: 'imitate_others',
    patterns: [
      /(模仿|照着|仿照|学(着)?|写成|按).{0,10}(风格|语气|口吻|调性|腔调|文风)/,
      /(像|像点|像一些).{0,8}(博主|大V|公众号|爆款)/,
    ],
    concern: '改成别人的语气，这篇文章就不再是你写的了',
    why: '视界的目标是"用户愿意发布的作品"，而不是"像某个成功样本的文章"。模仿会同时丢掉你的表达习惯和你原本的观点角度',
    better: '如果你喜欢的是某个具体手法（比如"用亲身经历开场"），我们可以只把那个手法融进来，其余保持你的说法',
  },
  {
    id: 'blanket_rewrite',
    patterns: [/(整个|全部|整篇|从头)(重写|推翻|重来|推翻重写)/, /(推倒|推翻)重来/],
    concern: '整篇重写会连你已经满意的部分一起丢掉',
    why: '重写是"再生成一篇"，不是"改这一篇"。上一版里被认可的表达、结构、案例都会被覆盖',
    better: '先说清楚哪几段不满意——局部改能保住其余部分，改完还能对比哪一版更好；确实要重来的话我也可以直接开始',
  },
]

/** 反馈低于该长度不做守门：单词没有"改法"可言 */
const MIN_TEXT_FOR_GUARD = 4

/**
 * 评估一次修改要求是否存在确定性风险。
 *
 * 无风险返回 null（调用方不展示任何提示——没有提示比"每次都提示"更重要）。
 */
export function assessRevisionRequest(freeText: string): AgentAdvisory | null {
  const text = (freeText ?? '').trim()
  if (text.length < MIN_TEXT_FOR_GUARD) return null

  for (const rule of GUARD_RULES) {
    for (const p of rule.patterns) {
      if (p.test(text)) {
        return { ruleId: rule.id, concern: rule.concern, why: rule.why, better: rule.better }
      }
    }
  }
  return null
}
